const VIEWPORT_MARGIN = 8;
const MENU_GAP = 8;
const MENU_WIDTH = 224;
const MENU_ITEM_HEIGHT = 44;
const DEFAULT_LANGUAGE = "en";
const RTL_LANGUAGES = ["ar", "fa", "he", "ur"];

function updateDocumentDirection(language: string): void {
  const isRTL = RTL_LANGUAGES.includes(language);

  document.documentElement.setAttribute(
    "dir",
    isRTL ? "rtl" : "ltr"
  );

  document.documentElement.setAttribute("lang", language);
}

const WRAPPER_ID = "gtranslate_widget";
const SCRIPT_SELECTOR = 'script[data-gtranslate-widget="true"]';
const SCRIPT_URL = "https://cdn.gtranslate.net/widgets/latest/dropdown.js";

function getValidLanguage(code?: string | null): string {
  return languages.find((language) => language.code === code)?.code ?? DEFAULT_LANGUAGE;
}

function detectBrowserLanguage(): string {
  const locales = navigator.languages?.length ? navigator.languages : [navigator.language];

  for (const locale of locales) {
    const normalized = locale.replace(/_/g, "-").toLowerCase();

    const exactMatch = languages.find(
      (language) => language.code.toLowerCase() === normalized,
    );
    if (exactMatch) return exactMatch.code;

    const baseLanguage = normalized.split("-")[0];
    const baseMatch = languages.find(
      (language) => language.code.toLowerCase() === baseLanguage,
    );
    if (baseMatch) return baseMatch.code;
  }

  return DEFAULT_LANGUAGE;
}

function getCookieLanguage(): string | null {
  const match = document.cookie.match(/(?:^|;\s*)googtrans=([^;]+)/);
  if (!match) return null;

  try {
    const parts = decodeURIComponent(match[1]).split("/");
    return getValidLanguage(parts[parts.length - 1]);
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

/**
 * GTranslate uses the googtrans cookie to persist the selected language.
 * Use one host-only cookie to avoid conflicting host/domain cookie values.
 */
function setTranslateCookie(language: string): void {
  document.cookie = [
    `googtrans=/en/${language}`,
    "path=/",
    "max-age=31536000",
    "SameSite=Lax",
  ].join(";");
}

function ensureGTranslateWrapper(): void {
  let wrapper = document.getElementById(WRAPPER_ID);

  if (!wrapper) {
    wrapper = document.createElement("div");
    wrapper.id = WRAPPER_ID;
    document.body.appendChild(wrapper);
  }

  // Keep the native selector available to GTranslate, but visually hidden.
  Object.assign(wrapper.style, {
    position: "fixed",
    left: "-10000px",
    top: "0",
    width: "1px",
    height: "1px",
    overflow: "hidden",
    opacity: "0",
    pointerEvents: "none",
  });

  wrapper.setAttribute("aria-hidden", "true");
}

function getGTranslateSelector(): HTMLSelectElement | null {
  return document.querySelector<HTMLSelectElement>(
    `#${WRAPPER_ID} select.gt_selector`,
  );
}

/**
 * Apply a language through the selector generated by the current GTranslate
 * dropdown.js widget. This is the selector confirmed in the user's browser.
 */
function applyGTranslateLanguage(language: string): boolean {
  const selector = getGTranslateSelector();
  if (!selector) return false;

  const optionValue = `en|${language}`;
  const optionExists = Array.from(selector.options).some(
    (option) => option.value === optionValue,
  );

  if (!optionExists) return false;

  selector.value = optionValue;
  selector.dispatchEvent(new Event("change", { bubbles: true }));
  return true;
}

function checkGTranslate() {
  const script = document.querySelector<HTMLScriptElement>(SCRIPT_SELECTOR);
  const selector = getGTranslateSelector();
  const cookie = document.cookie.match(/(?:^|;\s*)googtrans=([^;]+)/)?.[1] ?? null;

  const result = {
    settings: window.gtranslateSettings,
    scriptFound: Boolean(script),
    scriptLoaded: script?.dataset.loaded ?? "unknown",
    cookie,
    selectorFound: Boolean(selector),
    selectorValue: selector?.value ?? null,
    wrapperFound: Boolean(document.getElementById(WRAPPER_ID)),
  };

  console.table({
    "GTranslate settings present": Boolean(result.settings),
    "Script element found": result.scriptFound,
    "Script loaded": result.scriptLoaded,
    "Translation cookie": result.cookie ?? "Not found",
    "GTranslate selector found": result.selectorFound,
    "GTranslate selector value": result.selectorValue ?? "Unavailable",
    "Widget wrapper found": result.wrapperFound,
  });

  return result;
}

export default function LanguageButton({ className, showLabel=false, label='Language', variant="link" }: LanguageButtonProps) {
  const [open, setOpen] = useState(false);
  const [current, setCurrent] = useState(DEFAULT_LANGUAGE);
  useEffect(() => {
    updateDocumentDirection(current);
  }, [current]);

  const rootRef = useRef<HTMLDivElement>(null);
  const buttonRef = useRef<HTMLButtonElement>(null);
  const menuRef = useRef<HTMLDivElement>(null);

  const [position, setPosition] = useState({
    top: 0,
    left: VIEWPORT_MARGIN,
    width: MENU_WIDTH,
    maxHeight: 320,
    placement: "bottom" as "top" | "bottom",
  });

  const selectedLanguage =
    languages.find((language) => language.code === current) ?? languages[0];

  const syncLanguageWithWidget = useCallback((language: string) => {
    // The script can finish loading before or after the React component mounts.
    // Retry briefly while the widget creates its native select element.
    let attempts = 0;
    const maxAttempts = 20;

    const tryApply = () => {
      attempts += 1;

      if (applyGTranslateLanguage(language)) return;

      if (attempts < maxAttempts) {
        window.setTimeout(tryApply, 250);
      } else {
        console.warn(
          `[GTranslate] Could not find the widget selector to apply "${language}".`,
        );
      }
    };

    tryApply();
  }, []);

  // Initialize GTranslate once, before adding its script.
  useEffect(() => {
    window.gtranslateSettings = {
      default_language: DEFAULT_LANGUAGE,
      languages: languages.map((language) => language.code),
      wrapper_selector: `#${WRAPPER_ID}`,
    };

    window.checkGTranslate = checkGTranslate;
    ensureGTranslateWrapper();

    const savedLanguage = getCookieLanguage();
    const initialLanguage = savedLanguage ?? detectBrowserLanguage();
    setCurrent(initialLanguage);

    // On a first visit, save a non-English browser preference and reload once
    // so the widget can read the preference during its initial setup.
    if (savedLanguage === null && initialLanguage !== DEFAULT_LANGUAGE) {
      setTranslateCookie(initialLanguage);
      window.location.reload();
      return;
    }

    let script = document.querySelector<HTMLScriptElement>(SCRIPT_SELECTOR);

    if (!script) {
      script = document.createElement("script");
      script.src = SCRIPT_URL;
      script.async = true;
      script.dataset.gtranslateWidget = "true";

      script.addEventListener(
        "load",
        () => {
          script!.dataset.loaded = "true";
          console.info("[GTranslate] Widget script loaded.");
          syncLanguageWithWidget(initialLanguage);
        },
        { once: true },
      );

      script.addEventListener(
        "error",
        () => {
          script!.dataset.loaded = "false";
          console.error("[GTranslate] Failed to load widget script:", SCRIPT_URL);
        },
        { once: true },
      );

      document.body.appendChild(script);
    } else {
      // If the script already exists, wait for its selector to be available.
      syncLanguageWithWidget(initialLanguage);
    }

    const diagnosticTimer = window.setTimeout(() => {
      window.checkGTranslate?.();
    }, 2500);

    return () => window.clearTimeout(diagnosticTimer);
  }, [syncLanguageWithWidget]);

  // Keep the dropdown within the visible viewport on desktop and mobile.
  useEffect(() => {
    if (!open) return;

    const updatePosition = () => {
      const button = buttonRef.current;
      if (!button) return;

      const rect = button.getBoundingClientRect();
      const viewport = window.visualViewport;

      const viewportWidth = Math.min(
        document.documentElement.clientWidth,
        viewport?.width ?? window.innerWidth,
      );
      const viewportHeight = viewport?.height ?? window.innerHeight;
      const viewportTop = viewport?.offsetTop ?? 0;

      const width = Math.max(
        1,
        Math.min(MENU_WIDTH, viewportWidth - VIEWPORT_MARGIN * 2),
      );

      const availableBelow =
        viewportTop +
        viewportHeight -
        rect.bottom -
        MENU_GAP -
        VIEWPORT_MARGIN;

      const availableAbove =
        rect.top - viewportTop - MENU_GAP - VIEWPORT_MARGIN;

      const estimatedHeight = Math.min(
        languages.length * MENU_ITEM_HEIGHT + 12,
        viewportHeight - VIEWPORT_MARGIN * 2,
      );

      const placement: "top" | "bottom" =
        availableBelow >= estimatedHeight || availableBelow >= availableAbove
          ? "bottom"
          : "top";

      const maxHeight = Math.max(
        1,
        Math.min(
          placement === "bottom" ? availableBelow : availableAbove,
          viewportHeight - VIEWPORT_MARGIN * 2,
        ),
      );

      const left = Math.max(
        VIEWPORT_MARGIN,
        Math.min(rect.left, viewportWidth - width - VIEWPORT_MARGIN),
      );

      const top =
        placement === "bottom" ? rect.bottom + MENU_GAP : rect.top - MENU_GAP;

      setPosition({ top, left, width, maxHeight, placement });
    };

    updatePosition();

    window.addEventListener("resize", updatePosition);
    window.addEventListener("scroll", updatePosition, true);

    const viewport = window.visualViewport;
    viewport?.addEventListener("resize", updatePosition);
    viewport?.addEventListener("scroll", updatePosition);

    return () => {
      window.removeEventListener("resize", updatePosition);
      window.removeEventListener("scroll", updatePosition, true);
      viewport?.removeEventListener("resize", updatePosition);
      viewport?.removeEventListener("scroll", updatePosition);
    };
  }, [open]);

  // Close the menu on outside click or Escape.
  useEffect(() => {
    if (!open) return;

    const handlePointerDown = (event: PointerEvent) => {
      const target = event.target as Node;

      if (
        !rootRef.current?.contains(target) &&
        !menuRef.current?.contains(target)
      ) {
        setOpen(false);
      }
    };

    const handleKeyDown = (event: KeyboardEvent) => {
      if (event.key === "Escape") {
        setOpen(false);
        buttonRef.current?.focus();
      }
    };

    document.addEventListener("pointerdown", handlePointerDown);
    document.addEventListener("keydown", handleKeyDown);

    return () => {
      document.removeEventListener("pointerdown", handlePointerDown);
      document.removeEventListener("keydown", handleKeyDown);
    };
  }, [open]);

  function selectLanguage(code: string): void {
    const selectedCode = getValidLanguage(code);

    setOpen(false);
    if (selectedCode === current) return;

    setCurrent(selectedCode);
    setTranslateCookie(selectedCode);

    // Use the real selector created by dropdown.js. Reload only if the widget
    // has not finished creating its selector yet.
    const applied = applyGTranslateLanguage(selectedCode);

    if (!applied) {
      window.location.reload();
    }
  }

  const menuStyle: CSSProperties = {
    position: "fixed",
    left: position.left,
    width: position.width,
    maxHeight: position.maxHeight,
    zIndex: 9999,
    overscrollBehavior: "contain",
  };

  if (position.placement === "bottom") {
    menuStyle.top = position.top;
  } else {
    menuStyle.bottom = window.innerHeight - position.top + MENU_GAP;
  }

  return (
    <div ref={rootRef} className={cn("inline-flex", className)}>

      <button
        ref={buttonRef}
        type="button"
        onClick={() => setOpen((value) => !value)}
        aria-expanded={open}
        aria-haspopup="menu"
        aria-label={`Select language. Current language: ${selectedLanguage.label}`}
        title={`Language: ${selectedLanguage.label}`}
        className={cn(
          "flex h-[52px] items-center gap-3.5 rounded-xl",
          "px-3.5 text-[15px] font-medium",
          "transition-all duration-300 ease-out",

          // Link style - retain original styling
          variant === "link" && [
            "text-[#07164d]",
            "transition-colors hover:bg-[#ed1c24]/10 hover:text-[#ed1c24]",
            "focus-visible:outline-none focus-visible:ring-2",
            "focus-visible:ring-[#ed1c24]",
            open && "bg-[#ed1c24]/10 text-[#ed1c24]",
          ],

          // Bordered dropdown style
          variant === "button" && [
            "border border-[#07164d]/10",
            "bg-white/80 text-[#07164d]",
            "shadow-[0_2px_10px_rgba(7,22,77,0.035),0_0_12px_rgba(237,28,36,0.035)]",
            "hover:border-[#ed1c24]/30 hover:bg-white",
            "hover:text-[#ed1c24]",
            "hover:shadow-[0_3px_14px_rgba(237,28,36,0.10)]",
            "focus-visible:outline-none focus-visible:ring-2",
            "focus-visible:ring-[#ed1c24]/30",
            open &&
              "border-[#ed1c24]/35 bg-white text-[#ed1c24] shadow-[0_3px_16px_rgba(237,28,36,0.12)]",
          ],
        )}
      >
        <span className="grid w-[23px] shrink-0 place-items-center">
          <Globe
            size={18}
            strokeWidth={2}
            className="text-[#ed1c24]"
            aria-hidden="true"
          />
        </span>

        {showLabel && (
          <span className="min-w-0 truncate">
            {selectedLanguage.label || label}
          </span>
        )}
        
        {variant === "button" && showLabel && (
          <ChevronDown
            size={15}
            strokeWidth={1.8}
            className={cn(
              "ml-auto shrink-0 text-[#07164d]/50 transition-transform duration-300",
              open && "rotate-180 text-[#ed1c24]"
            )}
            aria-hidden="true"
          />
        )}
      </button>

      {open && (
        <>
          <button
            type="button"
            aria-label="Close language menu"
            tabIndex={-1}
            className="fixed inset-0 z-[9998] cursor-default bg-transparent"
            onClick={() => setOpen(false)}
          />

          <div
            ref={menuRef}
            role="menu"
            aria-label="Choose a language"
            style={menuStyle}
            className={cn(
              "overflow-y-auto rounded-xl border border-gray-200",
              "bg-white p-1.5 shadow-xl",
              "focus:outline-none",
            )}
          >
            {languages.map((language) => {
              const isSelected = current === language.code;

              return (
                <button
                  key={language.code}
                  type="button"
                  role="menuitem"
                  aria-current={isSelected ? "true" : undefined}
                  onClick={() => selectLanguage(language.code)}
                  className={cn(
                    "flex min-h-[44px] w-full items-center gap-3",
                    "rounded-lg px-3 py-2.5 text-left text-sm transition-colors",
                    isSelected
                      ? "bg-[#ed1c24]/10 font-semibold text-[#ed1c24]"
                      : "text-gray-700 hover:bg-[#ed1c24]/10 hover:text-[#ed1c24]",
                  )}
                >
                  <span className="shrink-0 text-xl" aria-hidden="true">
                    {language.flag}
                  </span>

                  <span className="min-w-0 flex-1 break-words">
                    {language.label}
                  </span>

                  {isSelected && (
                    <span
                      className="ml-auto shrink-0 text-[#ed1c24]"
                      aria-hidden="true"
                    >
                      ✓
                    </span>
                  )}
                </button>
              );
            })}
          </div>
        </>
      )}
    </div>
  );
}
